#!/usr/bin/env python3
"""
A-share trading calendar utility.

is_open(date) -> bool: whether the A-share market is open on the given date
Input: date string (YYYYMMDD) or unix timestamp (int/float)
Rule: closed on weekends + public holidays; open otherwise.

Holiday source: 国务院办公厅关于部分节假日安排的通知
Coverage: 2004 ~ 2027
"""

import time
from datetime import datetime, date


def isopen(val):
    """
    Check whether A-share market is open on the given date.

    val: date string (YYYYMMDD / YYYY-MM-DD) or unix timestamp (int/float)
    Returns: True if open, False if closed
    """
    # normalize input to date
    if isinstance(val, date):
        d = val
    elif isinstance(val, datetime):
        d = val.date()
    elif isinstance(val, (int, float)):
        # treat unix timestamp as +8 timezone, convert to UTC-equivalent date
        d = datetime.utcfromtimestamp(val + 8 * 3600).date()
    elif isinstance(val, str):
        s = val.strip().replace("-", "").replace("/", "")
        if len(s) == 8 and s.isdigit():
            d = datetime.strptime(s, "%Y%m%d").date()
        else:
            raise ValueError(f"unsupported date format: {val!r}")
    else:
        raise ValueError(f"unsupported date format: {val!r}")

    # weekend
    if d.weekday() >= 5:
        return False
    # public holiday
    if d.strftime("%Y%m%d") in HOLIDAYS:
        return False
    return True


